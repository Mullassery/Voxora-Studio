#!/usr/bin/env python
"""Generate the console TypeScript API client from the orchestrator's OpenAPI.

Usage: PYTHONPATH=services/orchestrator/src python services/orchestrator/scripts/generate_ts_client.py

Emits `apps/console/src/generated/apiTypes.ts` (schema types) and
`apps/console/src/generated/paths.ts` (path constants). The response *envelope*
shapes stay hand-typed in `api.ts` because the OpenAPI responses are untyped
(`additionalProperties: true`) — that is an honest limitation of the current
endpoint annotations, not a generator bug.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "apps/console/src/generated"

_SKIP_SCHEMAS = {"HTTPValidationError", "ValidationError"}


def build_app():
    from voxora.api import create_app
    from voxora.config import Settings, TenantPrincipal

    settings = Settings(
        env="test",
        database_path="/tmp/voxora-openapi-refresh.db",
        secret_key="unit-test-secret-key-must-be-32-chars",
        api_tokens={"codegen": TenantPrincipal("t", "admin", "Codegen")},
        seed_demo=False,
        worker_enabled=False,
    )
    return create_app(settings)


def ts_type(schema: Dict[str, Any]) -> str:
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    t = schema.get("type")
    if t == "string":
        enum = schema.get("enum")
        return " | ".join(json.dumps(v) for v in enum) if enum else "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if t == "object":
        return ts_object(schema)
    if t is None and schema.get("$ref") is None:
        if "anyOf" in schema:
            return " | ".join(ts_type(sub) for sub in schema["anyOf"])
        return "unknown"
    return "unknown"


def ts_object(schema: Dict[str, Any]) -> str:
    cleaned = {k: _clean_null_anyof(v) for k, v in (schema.get("properties") or {}).items()}
    schema = {**schema, "properties": cleaned}

    props = schema.get("properties") or {}
    if not props:
        return "Record<string, unknown>"
    parts = []
    for prop, sub in props.items():
        optional = "" if prop in (schema.get("required") or []) else "?"
        parts.append(f"{json.dumps(prop)}{optional}: {ts_type(sub)};")
    return "{ " + " ".join(parts) + " }"


def _clean_null_anyof(schema: Dict[str, Any]) -> Dict[str, Any]:
    """Fold anyOf [X, null] into a plain X|null anyOf the mapper handles."""
    any_of = schema.get("anyOf")
    if isinstance(any_of, list) and len(any_of) == 2:
        has_null = any(sub.get("type") == "null" for sub in any_of)
        if has_null:
            rest = [sub for sub in any_of if sub.get("type") != "null"]
            return {**schema, "anyOf": rest}
    return schema


def path_constant(path: str) -> str:
    def segment(part: str) -> str:
        if part.startswith("{"):
            name = part[1:-1].split("_")
            return "By" + "".join(word[0].upper() + word[1:] for word in name)
        words = part.replace("-", "_").split("_")
        return "".join(word[0].upper() + word[1:] for word in words)

    segments = path.replace("/api/v1/", "").split("/")
    return "PATH_" + "".join(segment(part) for part in segments if part)


def generate_paths(paths: Dict[str, Any]) -> List[str]:
    lines = [
        "// GENERATED by services/orchestrator/scripts/generate_ts_client.py — do not edit.",
        "// Source of truth: the orchestrator OpenAPI schema.",
        "",
    ]
    for path in sorted(paths):
        const_name = path_constant(path)
        if "{" in path:
            params = [part[1:-1] for part in path.split("/") if part.startswith("{")]
            template = path
            for param in params:
                template = template.replace("{" + param + "}", "${args." + param + "}")
            lines.append(
                f"export const {const_name} = (args: {{ "
                + " ".join(f"{p}: string;" for p in params)
                + " }): string => `" + template + "`;"
            )
        else:
            lines.append(f"export const {const_name} = {json.dumps(path)};")
    return lines


def main() -> int:
    spec = build_app().openapi()
    OUT.mkdir(parents=True, exist_ok=True)

    lines = [
        "// GENERATED by services/orchestrator/scripts/generate_ts_client.py — do not edit.",
        "// Source of truth: the orchestrator OpenAPI schema.",
        "",
    ]
    for name, schema in sorted(spec.get("components", {}).get("schemas", {}).items()):
        if name in _SKIP_SCHEMAS:
            continue
        lines.append(f"export type {name} = {ts_object(schema) if schema.get('type') == 'object' else ts_type(schema)};")
    types_path = OUT / "apiTypes.ts"
    types_path.write_text("\n".join(lines) + "\n")

    paths_path = OUT / "paths.ts"
    paths_path.write_text("\n".join(generate_paths(spec["paths"])) + "\n")
    print(f"generated {types_path} and {paths_path} from {len(spec['paths'])} paths")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
